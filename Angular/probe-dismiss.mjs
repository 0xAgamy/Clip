import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ ignoreHTTPSErrors: true });
const page = await ctx.newPage();
await page.goto('http://localhost:4200/', { waitUntil: 'networkidle' });
await page.waitForTimeout(1500);
await page.click('text=Login / Register');
await page.fill('app-modal input[type=email]', 'nobody@example.com');
await page.fill('app-modal input[type=password]', 'WrongPass123');
await page.locator('app-modal button[type=submit]').first().click();
await page.waitForTimeout(2500);
console.log('before dismiss:', JSON.stringify((await page.locator('app-modal app-form-alert').first().innerText()).trim()));
await page.locator('app-modal app-form-alert button[aria-label=Dismiss]').first().click();
await page.waitForTimeout(300);
console.log('after dismiss:', JSON.stringify((await page.locator('app-modal app-form-alert').first().innerText()).trim()));
await browser.close();
